import zipfile
import os
import pandas as pd
import json
import random
random.seed(0)
import shutil

'''
These were generated by prompting GPT-4o using:

I have about 100k image-caption pairs from medical context, I want to create an instruction tuning captioning dataset. Currently, all the prompts are of the same format: "Describe this medical image with relevant clinical findings.'"

Can you give me a list of 10 more similar prompts from which I can sample randomly to increase diversity.
'''
PROMPTS = [
    "Provide a detailed clinical interpretation of this medical image.",
    "Analyze the radiological findings visible in this image.",
    "Summarize the key abnormalities and clinical significance of this scan.",
    "What pathology or condition does this image most likely indicate?",
    "Explain the diagnostic findings based on this image.",
    "Interpret the medical image and highlight any relevant anatomical or pathological observations.",
    "Identify and describe any significant clinical features in this scan.",
    "Review the image and report notable radiologic signs or anomalies.",
    "Based on this image, what are the potential clinical implications?",
    "Describe the visual indicators of disease or trauma present in this medical image.",
    "Describe this medical image with relevant clinical findings.",
]

def json_to_jsonl(csv_filepath, jsonl_filepath, images_dir):
    json_data = pd.read_csv(csv_filepath).to_dict(orient="records")
    with open(jsonl_filepath, mode="w", encoding="utf-8") as jsonl_file:
        for id, item in enumerate(json_data):
            image_id = item["ID"] + ".jpg"
            image_path = os.path.join(images_dir, image_id)
            if os.path.exists(image_path):
                caption = item["Caption"].strip()
                image_beginning = random.choice([0, 1])
                prompt_ = random.choice(PROMPTS)
                if image_beginning:
                    jsonl_data = {
                        "id": id,
                        "image": f"imgs/{image_id}",
                        "conversations": [
                            {
                                "from": "human",
                                "value": f"<image>{prompt_}",
                            },
                            {"from": "gpt", "value": caption},
                        ],
                    }
                else:
                    jsonl_data = {
                        "id": id,
                        "image": f"imgs/{image_id}",
                        "conversations": [
                            {
                                "from": "human",
                                "value": f"{prompt_}<image>",
                            },
                            {"from": "gpt", "value": caption},
                        ],
                    }
                jsonl_file.write(json.dumps(jsonl_data) + "\n")
            else:
                print(f"Image not found: {image_path}")


def main():
    processed_dir = "./imageclef"

    print("Step 1: Downloading ImageClef2025 dataset")
    if not os.path.exists(f"{processed_dir}/imageclef2025.zip"):
        print(
            "Please download the dataset from https://drive.google.com/file/d/1ZJcd15D699x0WO3ZPS_3CessN2ed17qR/view?usp=drive_link and place it in ./imageclef/!"
        )
        exit(1)

    print("Step 2: Extracting ImageClef2025 dataset")
    with zipfile.ZipFile(
        os.path.join(processed_dir, "imageclef2025.zip"), "r"
    ) as zip_ref:
        zip_ref.extractall(processed_dir)
    with zipfile.ZipFile(
        os.path.join(processed_dir, "development/train/train.zip"), "r"
    ) as zip_ref:
        zip_ref.extractall(processed_dir)

    print("Step 3: Move the files")
    os.system(
        f"mv {processed_dir}/home/damm/clef/data/2025/splits/train {processed_dir}/imgs"
    )

    print("Step 4: Converting ImageClef2025 dataset to jsonl format")
    csv_filepath = f"{processed_dir}/development/train/train_captions.csv"
    jsonl_filepath = f"{processed_dir}/preprocessed.jsonl"
    images_dir = f"{processed_dir}/imgs"
    json_to_jsonl(csv_filepath, jsonl_filepath, images_dir)

    print("Step 5: Remove unnecessary files and folders")
    shutil.rmtree(os.path.join(processed_dir, "__MACOSX"))
    shutil.rmtree(os.path.join(processed_dir, "development"))
    shutil.rmtree(os.path.join(processed_dir, "home"))
    os.remove(os.path.join(processed_dir, "imageclef2025.zip"))

if __name__ == "__main__":
    main()
