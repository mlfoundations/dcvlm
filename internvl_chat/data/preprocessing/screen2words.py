from huggingface_hub import snapshot_download
import pandas as pd
import os
import io
from PIL import Image
from tqdm import tqdm
import random
random.seed(0) # to ensure reproducibility while creating the dataset jsonl
import json
import shutil

############ Utility functions
'''
This function was generated by prompting GPT-4o with:

I have an image of a screenshot of a phone screen along with annotations for the name of the app , a set of captions briefly describing the contents of the screenshot, the category of the app (entertainment, education etc), the average rating of the app, and the approximate number of downloads.
I want to construct a synthetic caption that takes in each caption separately along with the name of the app, the category, number of downloads and average rating, and randomly constructs a holistic caption. Make sure that each caption definitively contains the category, name and caption, while you can randomly choose to include the number of downloads and average rating in each holistic caption. This will give us higher diversity in the synthetic caption. You can first create some random prompts that you can fill in with the name of the app, a few more random prompts in which you can fill in the category, and also more random prompts for the average rating and the number of downloads. After that, you can randomly decide which order to concatenate the different parts of the caption. Write a simple python function for this that takes in the caption description, app name, the category, the number of downloads, and the average rating, and creates this holistic caption.
'''
def generate_synthetic_caption(app_name, category, captions, downloads=None, rating=None):
    """
    Generates a synthetic caption by combining the app name, category, captions, 
    and optionally including downloads and rating in a randomized manner.

    Args:
        app_name (str): Name of the app.
        category (str): Category of the app (e.g., entertainment, education).
        captions (list): List of caption descriptions extracted from the image.
        downloads (str, optional): Approximate number of downloads (e.g., "10M+").
        rating (str, optional): Average rating of the app (e.g., "4.5 stars").

    Returns:
        str: A randomly constructed holistic caption.
    """

    app_name = app_name.strip()
    category = category.strip()
    downloads = downloads.strip()
    rating = str(rating).strip()

    # App Name Templates
    app_name_templates = [
        f"Experience {app_name}, a leading app in its space.",
        f"Discover {app_name}, an innovative solution for users.",
        f"{app_name} is redefining the way users interact with {category} apps.",
        f"With {app_name}, users get an intuitive and seamless experience.",
        f"{app_name} stands out as a must-have {category} app."
    ]

    # Category Templates
    category_templates = [
        f"This {category} app provides top-notch features for users.",
        f"As a {category} app, it brings powerful functionality to its users.",
        f"A remarkable addition to the {category} category, enhancing user experiences.",
        f"The perfect {category} app for those looking for efficiency and ease.",
        f"Designed for {category}, this app ensures an engaging experience."
    ]

    # Download Count Templates (Optional)
    download_templates = [
        f"With over {downloads} downloads, it has gained immense popularity.",
        f"Join {downloads} users who have already discovered its benefits.",
        f"{downloads} downloads and counting – a testament to its impact.",
        f"Downloaded {downloads} times, it continues to impress users.",
        f"A massive hit with {downloads} downloads and growing daily."
    ] if downloads else []

    # Average Rating Templates (Optional)
    rating_templates = [
        f"With an impressive {rating} rating, users love this app.",
        f"Rated {rating} by thousands, it's a trusted choice.",
        f"Users have rated it {rating}, highlighting its quality.",
        f"A consistent {rating} rating shows its reliability.",
        f"Boasting a {rating} rating, it's a top-rated app in its category."
    ] if rating else []

    # Select random elements
    app_name_text = random.choice(app_name_templates)
    category_text = random.choice(category_templates)
    caption_text = random.choice(captions)
    assert caption_text is not None, "Caption text is None!!!"
    assert caption_text != "", "Caption text is empty!!!"
    if caption_text and caption_text[-1] not in {'.', '?'}:
        caption_text = caption_text + '.'

    # Optionally select a rating and download text
    optional_components = []
    if downloads and random.choice([True, False]):  # 50% chance to include downloads
        optional_components.append(random.choice(download_templates))
    if rating and random.choice([True, False]):  # 50% chance to include rating
        optional_components.append(random.choice(rating_templates))

    # Combine required and optional components
    parts = [app_name_text, category_text, caption_text] + optional_components
    random.shuffle(parts)  # Shuffle for diversity

    # Generate final caption
    synthetic_caption = " ".join(parts).strip()
    
    return synthetic_caption

'''
These were generated by prompting GPT-4o in the same conversation as the above prompt with:

Now I also want to create a prompt in a Q/A format that would succinctly ask a question such that the synthetic captions we generated would be a good for this prompt. Can you give me a python list of 10-15 random such prompts?
'''
QA_PROMPTS = [
    "Can you describe this app and its features briefly?",
    "What can you tell me about this app in one sentence?",
    "How would you introduce this app to a new user?",
    "What makes this app stand out in its category?",
    "Can you summarize the key features of this app?",
    "Why should someone consider using this app?",
    "What are some highlights of this app in its category?",
    "How would you describe this app to someone unfamiliar with it?",
    "What is this app about and why is it popular?",
    "Can you give a short overview of this app?",
    "What should users know about this app before downloading it?",
    "What are the main selling points of this app?",
    "What makes this app a good choice for users?",
    "How does this app compare to others in the same category?",
    "Why has this app gained so many downloads and high ratings?"
]

snapshot_download(
    repo_id="rootsautomation/RICO-Screen2Words",
    repo_type="dataset",
    allow_patterns=["data/train-*parquet"], # only download train parquets
    local_dir="screen2words_parquets"
)

output_dir = "./screen2words/images"
os.makedirs(output_dir, exist_ok=True)

new_jsonl_entries = []
imgs_saved = 0
parquets = [x for x in os.listdir("./screen2words_parquets/data") if x.endswith(".parquet")]
for parquet_index, parquet in enumerate(tqdm(parquets, ascii=True)):
    df = pd.read_parquet(os.path.join("./screen2words_parquets/data", parquet))
    for sample_index, row in tqdm(df.iterrows(), ascii=True):
        image = row["image"]
        captions = row["captions"]
        app_name = row["play_store_name"]
        category = row["category"]
        rating = row["average_rating"]
        num_downloads = row["number_of_downloads"]

        assert image is not None, 'image is None!!!'
        assert "bytes" in image, 'bytes not in image!!!'
        assert captions is not None, 'captions is None!!!'
        assert app_name is not None, 'app-name is None!!!'
        assert category is not None, 'category is None!!!'
        assert rating is not None, 'rating is None!!!'
        assert num_downloads is not None, 'downloads is None!!!'

        synthetic_caption = generate_synthetic_caption(app_name, category, captions, downloads=num_downloads, rating=rating)

        # save image
        img_bytes = image["bytes"]  # Extract the byte content
        image_ = Image.open(io.BytesIO(img_bytes)).convert('RGB')  # Convert bytes to an image
        file_name = f"{output_dir}/parquet_{parquet_index}_sample_{sample_index}_id_{imgs_saved}.png"  # Generate a unique name
        width, height = image_.size  # Get width and height
        image_.save(file_name)  # Save the image
        imgs_saved += 1

        assert file_name is not None, 'no images actually present for sample in parquet {}, sample {}'.format(parquet_index, sample_index)
        assert height is not None, 'no images actually present for sample in parquet {}, sample {}'.format(parquet_index, sample_index)
        assert width is not None, 'no images actually present for sample in parquet {}, sample {}'.format(parquet_index, sample_index)
        
        image_beginning = random.choice([0, 1]) # randomly pick if image comes at the beginning or at the end of the user prompt, this is to prevent overfitting to one style of prompting
        if image_beginning:
            convs = [{"from":"human", "value":"<image>{}".format(random.choice(QA_PROMPTS))}, {"from":"gpt", "value":synthetic_caption}]
        else:
            convs = [{"from":"human", "value":"{}<image>".format(random.choice(QA_PROMPTS))}, {"from":"gpt", "value":synthetic_caption}]

        entry_ = {"id":len(new_jsonl_entries), "image": 'images/'+os.path.basename(file_name), "height": height, "width": width, "conversations": convs}
        new_jsonl_entries.append(entry_)

with open(os.path.join('screen2words', 'preprocessed.jsonl'), 'w') as f:
    for entry in new_jsonl_entries:
        f.write(json.dumps(entry) + '\n')

shutil.rmtree('screen2words_parquets')

print("Preprocessing complete! Saved as 'screen2words/preprocessed.jsonl' with {} saved images in {} and {} total samples.".format(imgs_saved, output_dir, len(new_jsonl_entries)))
